    m = re.search(r'"results":\s*(\[.*?\])\s*,\s*"success"', out, re.S)
    if not m:
        m = re.search(r'"results":\s*(\[.*?\])\s*\]', out, re.S)
    return json.loads(m.group(1)) if m else []

