def map_kp(content):
    for pat, no in RULES:
        if re.search(pat, content):
            return f"jkp-{no:04d}"
    return None

rows = d1("SELECT id, content FROM questions WHERE subject='math' AND stage='初中'")
print(f"初中题目总数: {len(rows)}")
mapped = {}; unmapped = []
for r in rows:
    kp = map_kp(r["content"])
    if kp:
        mapped.setdefault(kp, []).append(r["id"])
    else:
        unmapped.append(r["id"])
print(f"已映射: {sum(len(v) for v in mapped.values())} 题, 覆盖知识点 {len(mapped)} 个")
print(f"未映射: {len(unmapped)} 题")
for uid in unmapped[:10]:
    s = d1(f"SELECT content FROM questions WHERE id='{uid}'")
    print(f"  {uid}: {s[0]['content'][:60] if s else '?'}")
